# backend/agents/evaluation_agent.py

from services.llm import llm

def evaluate_quiz(quiz_text: str, student_answers: str) -> str:
    """
    Evaluate a student's quiz answers against the original quiz
    (generated by Quiz Agent), and return a score + weak topics.

    Since Quiz Agent currently returns plain text (not structured JSON),
    we use the LLM itself to interpret both the quiz and the student's
    answers together, rather than trying to manually parse free text.
    """

    prompt = f"""
You are an exam evaluator for StudyPilot AI.

Below is a quiz (with correct answers) and a student's submitted answers.
Compare them carefully and return your evaluation in this EXACT format:

Score: X/Y
Percentage: Z%
Topic-wise Feedback:
- [Question topic]: Correct/Incorrect

Overall Weak Topics: [list topics the student got wrong, comma-separated. Write "None" if all correct]

Quiz (with correct answers):
{quiz_text}

Student's Submitted Answers:
{student_answers}
"""

    response = llm.invoke(prompt)

    return response.content